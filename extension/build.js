#!/usr/bin/env node
/*
 * Tangent Reader — compile-time target switch.
 *
 *   node build.js tangent            build the built-in extension used by the Tangent Android app
 *   node build.js tangent --check    verify the committed app asset matches src/ (no write; CI guard)
 *   node build.js standard           build the standalone desktop (Chrome/Firefox MV3) extension
 *
 * Both targets share ONE extractor (src/extractor.core.js — the pure tangentExtractArticle heuristic).
 * Only the transport glue and manifest differ:
 *
 *   tangent  = extractor.core + glue.tangent  (hands blocks to the native app over a Port; rules are
 *              pushed at runtime by ReaderPortHandler, so nothing is bundled). Output overwrites the
 *              app's shipping asset app/src/main/assets/extensions/reader/, which is where GeckoView
 *              installs it. Keep it byte-for-behaviour identical to what the app expects.
 *
 *   standard = extractor.core + bundled rules + reader CSS + render.js + glue.standard, injected on a
 *              toolbar click by background.js. Output lands in dist/standard/, loadable unpacked.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const REPO = path.resolve(ROOT, '..');
const SRC = path.join(ROOT, 'src');
const RULES_JSON = path.join(REPO, 'app/src/main/assets/reader_rules.json');
const APP_EXT_DIR = path.join(REPO, 'app/src/main/assets/extensions/reader');

const read = (p) => fs.readFileSync(p, 'utf8');
const banner = '/* GENERATED by extension/build.js — edit src/ then rebuild, do not edit here. */\n';

// Write only when content actually changed, so repeated builds (e.g. the Gradle hook on every
// compile) never churn a tracked file's mtime. Returns true iff a write happened.
function writeIfChanged(p, content) {
  try { if (fs.existsSync(p) && fs.readFileSync(p, 'utf8') === content) return false; } catch (e) {}
  fs.writeFileSync(p, content);
  return true;
}

/**
 * Mirror ReaderRules.parseRuleset / readerExtract.compactRules: emit the compact rules[] array
 * (match/include/strip only), dropping comment/whitespace-polluted entries. This is what the app
 * pushes over the port at runtime; the standalone build has no app, so it bakes the rules in.
 */
function compactRules() {
  const doc = JSON.parse(read(RULES_JSON));
  const clean = (v) => {
    const items = Array.isArray(v) ? v : (typeof v === 'string' ? [v] : []);
    return items.map((s) => String(s).trim())
      .filter((s) => s && !s.includes('//') && !s.includes('\n') && !s.includes('\r'));
  };
  const out = [];
  for (const r of (doc.rules || [])) {
    const match = clean(r.match);
    if (!match.length) continue;
    const o = { match };
    const inc = clean(r.include); if (inc.length) o.include = inc;
    const strip = clean(r.strip); if (strip.length) o.strip = strip;
    out.push(o);
  }
  return out;
}

function buildTangent(check) {
  const extractor = read(path.join(SRC, 'extractor.core.js')).replace(/\s+$/, '') + '\n\n' +
    read(path.join(SRC, 'glue.tangent.js')).replace(/^\s+/, '');
  const manifest = read(path.join(SRC, 'manifest.tangent.json'));

  const extOut = path.join(APP_EXT_DIR, 'extractor.js');
  const manOut = path.join(APP_EXT_DIR, 'manifest.json');

  if (check) {
    const drift = [];
    if (read(extOut).trim() !== extractor.trim()) drift.push('extractor.js');
    if (read(manOut).trim() !== manifest.trim()) drift.push('manifest.json');
    if (drift.length) {
      console.error(`✗ tangent asset out of sync with src/: ${drift.join(', ')}`);
      console.error('  run: node extension/build.js tangent');
      process.exit(1);
    }
    console.log('✓ tangent asset in sync with extension/src/');
    return;
  }

  const wrote = [];
  if (writeIfChanged(extOut, extractor)) wrote.push('extractor.js');
  if (writeIfChanged(manOut, manifest)) wrote.push('manifest.json');
  console.log(`✓ tangent built → ${path.relative(REPO, APP_EXT_DIR)}/`);
  console.log(wrote.length ? `  updated: ${wrote.join(', ')}` : '  already up to date (no write)');
}

function buildStandard() {
  const outDir = path.join(ROOT, 'dist', 'standard');
  fs.mkdirSync(outDir, { recursive: true });

  const rules = compactRules();
  const css = read(path.join(SRC, 'reader.css'));

  const bundle = [
    banner,
    read(path.join(SRC, 'extractor.core.js')).replace(/\s+$/, ''),
    '\n\n/* ---- bundled per-site rules (compacted from app/src/main/assets/reader_rules.json) ---- */',
    'var TANGENT_BUNDLED_RULES = ' + JSON.stringify(rules) + ';',
    '\n/* ---- reader overlay stylesheet (src/reader.css) ---- */',
    'var TANGENT_READER_CSS = ' + JSON.stringify(css) + ';',
    '\n/* ---- block -> DOM renderer (src/render.js) ---- */',
    read(path.join(SRC, 'render.js')).replace(/\s+$/, ''),
    '\n/* ---- toolbar-click overlay toggle (src/glue.standard.js) ---- */',
    read(path.join(SRC, 'glue.standard.js')).replace(/\s+$/, ''),
    '',
  ].join('\n');

  writeIfChanged(path.join(outDir, 'reader.bundle.js'), bundle);
  writeIfChanged(path.join(outDir, 'background.js'), banner + read(path.join(SRC, 'background.standard.js')));
  writeIfChanged(path.join(outDir, 'manifest.json'), read(path.join(SRC, 'manifest.standard.json')));
  // Static options page (auto-open setting) copied verbatim.
  writeIfChanged(path.join(outDir, 'options.html'), read(path.join(SRC, 'options.html')));
  writeIfChanged(path.join(outDir, 'options.js'), read(path.join(SRC, 'options.js')));

  console.log(`✓ standard built → ${path.relative(REPO, outDir)}/`);
  console.log(`  reader.bundle.js (${bundle.length} bytes, ${rules.length} site rules), background.js, manifest.json`);
  console.log('  load in Firefox: about:debugging#/runtime/this-firefox → Load Temporary Add-on → pick manifest.json');
}

const target = process.argv[2];
const check = process.argv.includes('--check');
if (target === 'tangent') buildTangent(check);
else if (target === 'standard') buildStandard();
else {
  console.error('usage: node build.js <tangent|standard> [--check]');
  process.exit(1);
}
